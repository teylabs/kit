import { createApp } from 'vue';
import './app.css';
import { initializeTheme } from '@/components/Kit/Appearance/useAppearance';
import AddressApp from './AddressApp.vue';
import AppearanceApp from './AppearanceApp.vue';
import App from './App.vue';
import FormAttrsApp from './FormAttrsApp.vue';
import FormStatusApp from './FormStatusApp.vue';
import SegmentedApp from './SegmentedApp.vue';
import TagsApp from './TagsApp.vue';
import WorkbenchApp from './WorkbenchApp.vue';
import MoneyApp from './MoneyApp.vue';
import WorkbenchMenuApp from './WorkbenchMenuApp.vue';
import StickyToastApp from './StickyToastApp.vue';
import WorkbenchReorderApp from './WorkbenchReorderApp.vue';
import DateTimeApp from './DateTimeApp.vue';
import PickersApp from './PickersApp.vue';

const query = new URLSearchParams(window.location.search);
if (query.has('appearance')) initializeTheme();
createApp(query.has('appearance') ? AppearanceApp : query.has('pickers') ? PickersApp : query.has('datetime') ? DateTimeApp : query.has('address') ? AddressApp : query.has('money') ? MoneyApp : query.has('segmented') ? SegmentedApp : query.has('sticky-toast') ? StickyToastApp : query.has('form-attrs') ? FormAttrsApp : query.has('form-status') ? FormStatusApp : query.has('tags') ? TagsApp : query.has('workbench-menu') ? WorkbenchMenuApp : query.has('workbench-reorder') ? WorkbenchReorderApp : query.has('workbench') ? WorkbenchApp : App).mount('#app');
